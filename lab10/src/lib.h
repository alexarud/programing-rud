/**
 * @file lib.h
 * @brief Бібліотека для роботи з матрицями та масивами
 * 
 * Цей файл містить оголошення функцій для роботи з квадратними матрицями
 * та масивами цілих чисел, включаючи операції копіювання діагоналі,
 * сортування та виведення даних.
 * 
 */
#ifndef LIB_H
#define LIB_H


/**
 * @brief Копіює головну діагональ квадратної матриці у масив.
 *
 * Функція проходить по елементах matrix[i][i] та записує їх
 * у масив diag. Матриця має бути квадратною n×n.
 *
 * @param matrix Двовимірний масив (int**), що містить матрицю n×n.
 * @param n Розмір квадратної матриці.
 * @param diag Масив, у який буде скопійовано n елементів діагоналі.
 */
void copy_main_diagonal(int **matrix, int n, int *diag);

/**
 * @brief Сортує масив цілих чисел за зростанням.
 *
 * Реалізовано через простий алгоритм порівнянь (подвійний цикл).
 *
 * @param arr Масив для сортування.
 * @param n Кількість елементів у масиві.
 */
void sort_array(int *arr, int n);

/**
 * @brief Друкує квадратну матрицю n×n у стандартний вихідний потік.
 *
 * Використовується для відлагодження. Кожен рядок друкується
 * на окремому рядку, елементи розділені табуляцією.
 *
 * @param matrix Двовимірний масив (int**), що містить матрицю.
 * @param n Розмірність квадратної матриці.
 */
void print_matrix(int **matrix, int n);

/**
 * @brief Друкує масив цілих чисел у стандартний вихідний потік.
 *
 * Елементи виводяться через пробіл.
 *
 * @param arr Масив для виведення.
 * @param n Кількість елементів масиву.
 */
void print_array(int *arr, int n);

#endif
