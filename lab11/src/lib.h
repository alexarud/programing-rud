/**
 * @file lib.h
 * @brief Бібліотека для побудови трикутника Паскаля
 *
 * Містить оголошення функцій для ітеративної та рекурсивної побудови
 * трикутника Паскаля та управління пам'яттю.
 */
#ifndef LIB_H
#define LIB_H

/**
 * @brief Обчислює біноміальний коефіцієнт рекурсивно C(n, k).
 *
 * Базові випадки: C(n,0) = C(n,n) = 1.
 * Рекурентне співвідношення: C(n,k) = C(n-1,k-1) + C(n-1,k).
 *
 * @param n Номер рядка (починаючи з 0).
 * @param k Позиція в рядку (від 0 до n включно).
 * @return Значення біноміального коефіцієнта C(n, k).
 */
int pascal_recursive(int n, int k);

/**
 * @brief Будує трикутник Паскаля ітеративно.
 *
 * Виділяє динамічну пам'ять для n рядків, де рядок i містить (i+1) елементів.
 * Доступ до елементів здійснюється через розіменування покажчиків.
 *
 * @param n Кількість рядків трикутника (>= 1).
 * @return Вказівник int** на побудований трикутник, або NULL у разі помилки.
 */
int **pascal_iterative(int n);

/**
 * @brief Звільняє пам'ять, виділену для трикутника Паскаля.
 *
 * @param triangle Вказівник на трикутник Паскаля (int**).
 * @param n Кількість рядків.
 */
void free_pascal(int **triangle, int n);

#endif
